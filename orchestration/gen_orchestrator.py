LINES.append("# 1. Resolution des paths via KORX (GF-09 : pas de hardcodage)")
LINES.append("#-------------------------------------------------------------------------------")
LINES.append("function Resolve-AllTargets {")
LINES.append("  $targets = @{}")
LINES.append("  $targetList = if ($Target -eq 'all') { @('skills','citizens','loopx') } else { @($Target) }")
LINES.append("")
LINES.append("  foreach ($t in $targetList) {")
LINES.append("    $json = & powershell -NoProfile -ExecutionPolicy Bypass -File \"$PSScriptRoot\\korx-path-resolver.ps1\" -Target $t")
LINES.append("    $parsed = $json | ConvertFrom-Json")
LINES.append("    if ($parsed.Error) {")
LINES.append("      Write-Warning \"Impossible de resoudre $t : $($parsed.Error)\"")
LINES.append("      continue")
LINES.append("    }")
LINES.append("    $targets[$t] = $parsed.PhysicalPath")
LINES.append("  }")
LINES.append("  return $targets")
LINES.append("}")
LINES.append("")
LINES.append("#-------------------------------------------------------------------------------")
LINES.append("# 2. Protection des dossiers systeme (GF-03)")
LINES.append("#-------------------------------------------------------------------------------")
LINES.append("function Test-IsProtectedPath {")
LINES.append("  param([string]$Path)")
LINES.append("  $protected = @('.git', '.kilo', 'node_modules', '.gitkeep')")
LINES.append("  $name = Split-Path $Path -Leaf")
LINES.append("  return $protected -contains $name")
LINES.append("}")
